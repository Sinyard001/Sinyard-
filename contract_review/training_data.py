# 通用性前后缀。全部类别统一使用，避免模型依赖前缀措辞。
_GENERIC_PREFIXES = [
    "",
    "经双方协商一致，",
    "双方确认，",
    "如无特别约定，",
    "本合同项下，",
    "根据本合同的约定，",
    "特别说明如下：",
    "",
]


def build_training_corpus():
    """生成 (条款文本, 类别) 训练数据。"""
    corpus = []
    for category, seeds in _SEED_EXAMPLES.items():
        for seed in seeds:
            for prefix in _GENERIC_PREFIXES:
                text = prefix + seed
                if text.endswith("。"):
                    pass
                corpus.append((text, category))
    return corpus


